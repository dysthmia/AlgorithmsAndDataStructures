# Дан массив а1, а2,..., an. Требуется определить, можно ли его разбить 
# на n - 1 множество таким образом, что:
# 1) Каждый из элементов массива принадлежит ровно одному из множеств.
# 2) В каждом из n - 1 множеств сумма элементов равна.

# Входные данные
# В первой строке записано число n (3 ≤ п ≤ 10) - длина массива.
# Во второй строке записано n чисел a1, а2,..., аn (1 ≤ 0; ≤ 100) - элементы массива.

# Выходные данные
# Если массив можно разбить на n — 1 множество таким образом, чтобы в каждом из множеств 
# сумма элементов была равна, выведите <<YES>>, в противном случае выведите <<N0>>.

def Solve():
    n = int(input())
    arr = [int(x) for x in input().split()]

    total_sum = sum(arr)
    if (total_sum%(n-1)!=0):
        print("NO")
        return

    target_sum = total_sum//(n-1)
    
    not_target = []
    for x in arr:
        if (x != target_sum):
            not_target.append(x)
            if (len(not_target)>2):
                print("NO")
                return

    if (len(not_target)!=2):
        print("NO")
        return
    
    if (sum(not_target)!=target_sum):
        print("NO")
        return
    
    print("YES")

Solve()


# Так как всего n элементов, а групп ровно n-1, то по принципу Дирихле 
# ровно одна группа будет содержать два элемента, а все остальные n-2 группы 
# – по одному элементу.
# (Пустые группы невозможны, потому что все числа положительные, и сумма в 
# пустой группе была бы 0, а в остальных – положительной, что нарушило бы 
# равенство сумм.)

# Обозначим общую сумму массива через S = sum(a), а искомую сумму в каждой 
# группе через T. Тогда:
# Все n-2 группы из одного элемента дают вклад (n-2)·T;
# Одна группа из двух элементов даёт вклад T;
# Итого: S = (n-2)·T + T = (n-1)·T.

# Отсюда сразу следует необходимое условие:
# S должно нацело делиться на n-1, и тогда T = S / (n-1).

# Далее, если такое T существует, то для выполнения разбиения необходимо и достаточно, 
# чтобы в массиве были ровно n-2 элемента, равных T, а оставшиеся два элемента в сумме 
# давали T.
# (Эти два элемента не могут быть равны T, иначе их сумма была бы 2T > T, так как 
# числа положительные.)

# Таким образом, задача сводится к поиску пары индексов (i, j), таких что:
# a[i] + a[j] == T;
# все остальные элементы (кроме i и j) равны T.

